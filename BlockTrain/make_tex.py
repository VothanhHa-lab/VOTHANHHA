#!/usr/bin/env python3
"""Write text/A_results.tex. EVERY number is read from runs/main/*.csv / PROTOCOL.json."""
import os, json
import numpy as np, pandas as pd

ROOT = os.path.dirname(os.path.abspath(__file__))
RUN = os.path.join(ROOT, "runs", "main")
S = pd.read_csv(os.path.join(RUN, "metrics_summary.csv"))
P = pd.read_csv(os.path.join(RUN, "metrics_per_seed.csv"))
MC = pd.read_csv(os.path.join(RUN, "mc_sensitivity_summary.csv")).set_index("K")
BY = pd.read_csv(os.path.join(RUN, "metrics_by_anomaly.csv"))
PROT = json.load(open(os.path.join(ROOT, "runs", "PROTOCOL.json")))

MODELS = ["cnn", "bigru", "cnn_bigru", "cnn_bigru_att", "blocktrain"]
NAME = {"cnn": "CNN", "bigru": "BiGRU", "cnn_bigru": "CNN--BiGRU", "cnn_bigru_att": "CNN--BiGRU--Attention",
        "blocktrain": "BlockTrain"}
MET = ["f1", "auroc", "auprc", "brier", "nll", "ece"]
UP = {"f1": 1, "auroc": 1, "auprc": 1, "brier": 0, "nll": 0, "ece": 0}
mean = S.pivot(index="model", columns="metric", values="mean")
sd = S.pivot(index="model", columns="metric", values="sd")
lo = S.pivot(index="model", columns="metric", values="ci_boot_windows_lo")
hi = S.pivot(index="model", columns="metric", values="ci_boot_windows_hi")


def f(x, n=3):
    return f"{x:.{n}f}"


def ms(m, k, n=3):
    return f"{mean.loc[m, k]:.{n}f}$\\pm${sd.loc[m, k]:.{n}f}"


best = {k: (mean.loc[MODELS, k].idxmax() if UP[k] else mean.loc[MODELS, k].idxmin()) for k in MET}
rows = []
for m in MODELS:
    cells = []
    for k in MET:
        c = ms(m, k)
        cells.append(f"\\textbf{{{c}}}" if best[k] == m else c)
    rows.append(f"        {NAME[m]}\n        & " + " & ".join(cells) + " \\\\")
bl = lambda m, k: f"{mean.loc[m, k]:.3f}"
base_row = ("        Trivial baseline$^{\\dagger}$\n        & " + " & ".join([
    bl("all_positive", "f1"), bl("all_positive", "auroc"), bl("all_positive", "auprc"),
    bl("constant_prevalence", "brier"), bl("constant_prevalence", "nll"), bl("constant_prevalence", "ece")]) + " \\\\")

# paired comparison BlockTrain vs CNN-BiGRU-Attention (same weights), per seed
pa = P[P.model == "cnn_bigru_att"].set_index("seed"); pb = P[P.model == "blocktrain"].set_index("seed")
dd = {k: (pb[k] - pa[k]) for k in MET}
n_lower_auroc = int((dd["auroc"] < 0).sum()); n_seeds = len(pa)
rank = {k: mean.loc[MODELS, k].sort_values(ascending=bool(not UP[k])).index.tolist() for k in MET}
prev = S[(S.model == "all_positive") & (S.metric == "auprc")]["mean"].iloc[0]
thr_bt = pb["threshold"]
# per-type detection (fraction of windows predicted positive) at the validation threshold
g = BY[BY.anomaly_type.isin(["clean", "value_noise", "missing_block"])].groupby(["model", "anomaly_type"])["frac_predicted_positive"].mean()
ga = BY[BY.anomaly_type.str.startswith("auroc_")].groupby(["model", "anomaly_type"])["mean_prob"].mean()
n_test = int(P["n_test"].iloc[0])
ps = PROT["participant_split"]
rel = pd.read_csv(os.path.join(RUN, "figdata_reliability.csv"))
gap = {m: (rel[rel.model == m].acc_mean - rel[rel.model == m].conf_mean) for m in MODELS}
# bins 3..8 (mean predicted prob 0.3-0.9) where BlockTrain lies above diagonal
mid = {m: gap[m].iloc[3:9] for m in MODELS}
n_above_bt = int((gap["blocktrain"] > 0).sum())
n_above_att = int((gap["cnn_bigru_att"] > 0).sum())
hi_bins = {m: gap[m].iloc[6:9].mean() for m in MODELS}

assert all(rank[k][-1] == "blocktrain" for k in MET), "text claims BlockTrain is worst on all six metrics"
assert all(hi_bins[m] < 0 for m in ["cnn", "bigru", "cnn_bigru"]) and hi_bins["blocktrain"] > 0
assert best["f1"] == best["auroc"] == best["auprc"]
assert best['brier'] == best['nll'] == best['f1']
K = MC.index.tolist()
tex = []
A = tex.append
A("% =====================================================================")
A("% A_results.tex -- generated by work/make_tex.py from runs/main/*.csv (do not hand-edit numbers)")
A("% Replaces Sections 5.1-5.3, 5.7 and 5.9 of the old manuscript. Figures: work/figs/*.pdf (PNG 300 dpi also provided)")
A("% =====================================================================")
A("")
A("\\paragraph{Protocol used for the re-run (differences from the earlier manuscript).}")
A("All numbers below were regenerated with a single pipeline from saved prediction files "
  "(five seeds $\\{11,22,33,44,55\\}$, "
  f"{PROT['settings']['n_train']:,} training, {PROT['settings']['n_val']:,} validation and {PROT['settings']['n_test']:,} test windows per seed, "
  f"batch size {PROT['settings']['batch']}, at most {PROT['settings']['epochs']} epochs, early-stopping patience {PROT['settings']['patience']}). "
  "They do not reproduce, and should not be compared with, the numbers of the earlier manuscript version, because the "
  "earlier training script did not implement the protocol described in Sections~3--4. "
  "In particular, the controlled corruption in this re-run consists of two types only, \\emph{value noise} "
  "(Gaussian noise added to one channel over a contiguous segment of 10--30 steps) and \\emph{missing block} "
  "(a contiguous segment of 10--30 steps of one channel set to missing); this matches the earlier validation prediction files, "
  "which contain only the types value\\_noise and missing\\_block. Spike, flat-line and level-shift corruptions, "
  "which the earlier text listed, were not implemented in either run and must not be described as evaluated. "
  f"The participant partition is fixed ({len(ps['train'])} training, {len(ps['val'])} validation, {len(ps['test'])} test participants; "
  f"split seed {ps['rng_seed_used']} after redrawing seeds {', '.join(str(a['rng_seed']) for a in ps['attempts'] if not a['accepted'])} "
  "because a validation or test participant had fewer than 2000 valid windows). "
  "Test windows are half clean (label 0) and half corrupted (label 1), so the prevalence is 0.5 and the trivial baselines are "
  f"F1 $={f(mean.loc['all_positive','f1'])}$ (all-positive prediction), AUROC $={f(mean.loc['all_positive','auroc'])}$ and AUPRC $={f(prev)}$.")
A("")
A("% ------------------------------------------------------------------ 5.1")
A("\\subsection{Primary predictive performance}\\label{subsec:primary_results}")
A("")
A("Table~\\ref{tab:primary_results} reports the primary test performance (mean $\\pm$ standard deviation across the five seeds; "
  "the standard deviation is computed over seeds with $n-1$ in the denominator). The classification threshold of each model was chosen by maximising F1 on the validation windows and then fixed.")
A("")
A("\\begin{table}[htbp]")
A("    \\centering")
A("    \\caption{Primary test performance (mean $\\pm$ SD over five seeds; participant-independent test set, "
  f"{n_test:,} windows per seed, 50\\% corrupted). Higher is better for F1, AUROC and AUPRC; lower is better for Brier, NLL and ECE. "
  "Bold marks the best mean in each column. BlockTrain uses the same trained weights as CNN--BiGRU--Attention, evaluated with $K=10$ MC-dropout passes and U-Attention. "
  "$^{\\dagger}$Trivial baselines: all-positive classifier for F1 (AUROC $=0.5$, AUPRC $=$ prevalence), constant prediction equal to the prevalence for Brier, NLL and ECE.}")
A("    \\label{tab:primary_results}")
A("    \\resizebox{\\linewidth}{!}{%")
A("    \\begin{tabular}{lcccccc}")
A("        \\hline")
A("        Model & F1 $\\uparrow$ & AUROC $\\uparrow$ & AUPRC $\\uparrow$ & Brier $\\downarrow$ & NLL $\\downarrow$ & ECE $\\downarrow$ \\\\")
A("        \\hline")
tex += rows
A("        \\hline")
A(base_row)
A("        \\hline")
A("    \\end{tabular}}")
A("\\end{table}")
A("")
B = lambda m, k: f(mean.loc[m, k])
A(f"On the primary metrics the ranking by mean is {', '.join(NAME[m] for m in rank['auroc'])} for AUROC (best to worst). "
  f"{NAME[best['f1']]} has the highest mean F1 ({B(best['f1'],'f1')}), AUROC ({B(best['auroc'],'auroc')}) and AUPRC ({B(best['auprc'],'auprc')}). "
  f"BlockTrain obtains F1 {B('blocktrain','f1')}, AUROC {B('blocktrain','auroc')} and AUPRC {B('blocktrain','auprc')}, "
  f"i.e. the lowest mean of the five models on these three metrics. "
  f"Differences between models are of the same size as the seed-to-seed standard deviation "
  f"(SD of AUROC between {f(sd.loc[MODELS,'auroc'].min())} and {f(sd.loc[MODELS,'auroc'].max())}), so a ranking of the models is not established by five seeds.")
A("")
A(f"Because BlockTrain shares its weights with CNN--BiGRU--Attention, the two can be compared pair-wise per seed. "
  f"BlockTrain's AUROC was lower than that of the deterministic attention model in {n_lower_auroc} of {n_seeds} seeds "
  f"(mean paired difference {dd['auroc'].mean():+.3f}, SD {dd['auroc'].std(ddof=1):.3f}); the paired AUPRC difference was {dd['auprc'].mean():+.3f} "
  f"and the paired Brier difference {dd['brier'].mean():+.3f}. In this experiment MC-dropout inference with U-Attention therefore did \\emph{{not}} improve discrimination "
  "or probabilistic scores over the conventional model it is built on; it reduced them slightly but consistently. "
  "Whether the reduction comes from MC averaging or from the uncertainty re-weighting is addressed in the ablation (Section~\\ref{subsec:ablation}).")
A("")
A("All models separate corrupted from clean windows far better than chance, and the absolute level is much higher than reported in the earlier manuscript version "
  "(AUROC $\\approx 0.65$ there). The earlier numbers should be considered superseded. "
  "Detection is not uniform over corruption types: at the validation threshold, the fraction of corrupted windows flagged was "
  f"{f(g[('blocktrain','value_noise')],2)} for value noise and {f(g[('blocktrain','missing_block')],2)} for missing blocks for BlockTrain, "
  f"and {f(g[('blocktrain','clean')],2)} of the clean windows were flagged (file \\texttt{{metrics\\_by\\_anomaly.csv}}).")
