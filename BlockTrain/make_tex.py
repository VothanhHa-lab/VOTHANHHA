  f"BlockTrain lies above the diagonal in {n_above_bt} of 10 bins (the observed frequency exceeds the predicted probability, i.e.\\ it is under-confident for the corrupted class; mean gap {hi_bins['blocktrain']:+.3f} in the 0.6--0.9 bins), "
  f"and CNN--BiGRU--Attention in {n_above_att} of 10 bins. "
  "The MC-averaged probabilities are therefore not better calibrated than the deterministic ones in this experiment; they are shifted in the opposite direction. "
